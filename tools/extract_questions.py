"""Extract PSPO questions from the exam-prep PDF into questions.js.

Usage: python tools/extract_questions.py "doc/Professional Scrum Product Owner I Exam-Prep.pdf" questions.js
Requires: pip install pdfplumber

Questions listed in tools/flagged_questions.json (answer key judged wrong against the
Scrum Guide 2020) are left out, together with any repeated copy of them in the book.
"""
import re, json, sys, os
import pdfplumber

FLAGGED_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'flagged_questions.json')

# The book prints one option across two letters in these questions (e.g. "B. ... the application"
# / "C. of techniques ..."). Value = index of the first half; the next option is merged into it.
SPLIT_OPTIONS = {'T3Q41': 1, 'T5Q12': 1, 'T5Q44': 1}

with pdfplumber.open(sys.argv[1]) as pdf:
    text = '\n'.join('=====PAGE=====\n' + (p.extract_text() or '') for p in pdf.pages)
lines = text.split('\n')
start = next(i for i,l in enumerate(lines) if l.startswith('Chapter 2: PSPOTM I Full Mock Test 1') and i > 100)
end = next(i for i,l in enumerate(lines) if l.startswith('Chapter 9: Glossary') and i > start)
lines = [l.strip() for l in lines[start:end] if not l.startswith('=====PAGE')]

def join(parts):
    s = ''
    for p in parts:
        if not p: continue
        if s.endswith('-') and not s.endswith(' -'): s = s[:-1] + p   # hyphenated line break
        else: s = (s + ' ' + p) if s else p
    return re.sub(r'\s+', ' ', s).strip()

qs, test, cur, state = [], 0, None, None
def flush():
    if cur: qs.append(cur)
for l in lines:
    m = re.match(r'Chapter \d+: PSPOTM I (?:Full )?Mock Test (\d+)', l)
    if m: flush(); cur = None; test = int(m.group(1)); continue
    if l.startswith('Time Limit:'): continue
    m = re.match(r'Question (\d+):\s*(.*)', l)
    if m:
        flush()
        cur = {'test': test, 'num': int(m.group(1)), 'q': [m.group(2)], 'opts': [], 'ans': '', 'exp': []}
        state = 'q'; continue
    if cur is None: continue
    nxt = chr(ord('A') + len(cur['opts']))
    m = re.match(r'([A-H])\.\s*(.*)', l)
    if state in ('q', 'opt') and m and m.group(1) == nxt:
        cur['opts'].append([m.group(2)]); state = 'opt'; continue
    m = re.match(r'Answer:\s*(.*)', l)
    if m and state in ('q','opt'):
        cur['ans'] = m.group(1); state = 'ans'; continue
    if l == 'Explanation' and state == 'ans': state = 'exp'; continue
    if state == 'q': cur['q'].append(l)
    elif state == 'opt': cur['opts'][-1].append(l)
    elif state == 'exp': cur['exp'].append(l)
    elif state == 'ans' and l: cur['exp'].append(l)
flush()

out, bad = [], []
for c in qs:
    letters = re.findall(r'[A-H]', c['ans'])
    opts = [join(o) for o in c['opts']]
    q = join(c['q'])
    ok = letters and opts and all(ord(x)-65 < len(opts) for x in letters)
    if not ok: bad.append((c['test'], c['num'], c['ans'], len(opts))); continue
    qid = f"T{c['test']}Q{c['num']}"
    answer = sorted({ord(x)-65 for x in letters})
    if qid in SPLIT_OPTIONS:
        k = SPLIT_OPTIONS[qid]
        opts[k:k+2] = [opts[k] + ' ' + opts[k+1]]
        answer = sorted({a - 1 if a > k else a for a in answer})
    out.append({'id': qid, 'test': c['test'], 'num': c['num'], 'question': q,
                'options': opts, 'answer': answer, 'explanation': join(c['exp'])})
print('parsed', len(qs), 'kept', len(out), 'bad', bad, file=sys.stderr)

flagged_ids = {f['id'] for f in json.load(open(FLAGGED_PATH))}
flagged_text = {o['question'].lower() for o in out if o['id'] in flagged_ids}
removed = [o['id'] for o in out if o['id'] in flagged_ids or o['question'].lower() in flagged_text]
out = [o for o in out if o['id'] not in removed]
print('removed', len(removed), 'flagged/duplicate questions:', removed, file=sys.stderr)
from collections import Counter
print(Counter(len(o['options']) for o in out), Counter(o['test'] for o in out), file=sys.stderr)
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/extract_questions.py from the PSPO I Exam-Prep PDF.\n')
    f.write('window.QUESTIONS = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
